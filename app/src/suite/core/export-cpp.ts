import {
  resolveNodeConstraints,
  type Condition,
  type SuiteProject,
} from "./model.ts";
import { autoNext, isIntermediate } from "./runtime.ts";
/** Original header-only runtime export. No optimizer output or fixed trajectory clock. */
export function exportCpp(project: SuiteProject): string {
  const quoted = (text: string) =>
    '"' +
    [...new TextEncoder().encode(text)]
      .map((c) =>
        c === 34
          ? '\\"'
          : c === 92
            ? "\\\\"
            : c >= 32 && c < 127
              ? String.fromCharCode(c)
              : "\\" + c.toString(8).padStart(3, "0"),
      )
      .join("") +
    '"';
  const signal = (value: boolean | number | string) =>
    typeof value === "boolean"
      ? `mayhem::SignalValue{${value}}`
      : typeof value === "number"
        ? `mayhem::SignalValue{double{${value}}}`
        : `mayhem::SignalValue{std::string_view{${quoted(value)}}}`;
  const expression = (c: Condition): string => {
    if (c.kind === "always") return "std::optional<bool>{true}";
    if (c.kind === "signal")
      return `mayhem::Compare(h.Signal(${quoted(c.key)}), mayhem::CompareOp::${c.op === "eq" ? "Eq" : c.op === "gt" ? "Gt" : "Lt"}, ${signal(c.value)})`;
    if (c.kind === "not") return `mayhem::Not(${expression(c.condition)})`;
    return `mayhem::${c.kind === "all" ? "All" : "Any"}({${c.conditions.map(expression).join(", ")}})`;
  };
  const output = [
    "// Generated by Mayhem. Edit the project or your custom robot code, then regenerate.",
    `// Project ${project.id.replace(/[\r\n\u2028\u2029]/g, " ")} revision ${project.revision}. SI units, blue-origin coordinates.`,
    "#pragma once",
    "#include <array>",
    '#include "mayhem/auto_runner.hpp"',
    "namespace mayhem_generated {",
    `inline constexpr mayhem::Pose startPose{${project.robot.start.x},${project.robot.start.y},${project.robot.start.heading}};`,
  ];
  project.routines.forEach((r, ri) => {
    output.push(`namespace routine_${ri} {`);
    const start = r.start ?? project.robot.start;
    output.push(
      `inline constexpr mayhem::Pose startPose{${start.x},${start.y},${start.heading}};`,
    );
    r.transitions.forEach((t, i) =>
      output.push(
        `inline bool guard_${i}([[maybe_unused]] const mayhem::RobotHooks& h) { return (${expression(t.condition)}).value_or(false); }`,
      ),
    );
    r.nodes.forEach((n, i) => {
      const markers = n.goal?.markers ?? [];
      if (markers.length)
        output.push(
          `inline constexpr std::array<mayhem::PathMarker,${markers.length}> markers_${i} = {{${markers
            .map((m) =>
              m.kind === "rotation"
                ? `{mayhem::MarkerKind::Rotation,${m.t},${m.heading},{},${m.profiled ?? true}}`
                : `{mayhem::MarkerKind::Event,${m.t},0,std::string_view{${quoted(m.key)}},true}`,
            )
            .join(",")}}};`,
        );
      if (n.during?.length)
        output.push(
          `inline constexpr std::array<std::string_view,${n.during.length}> during_${i} = {${n.during.map(quoted).join(",")}};`,
        );
    });
    output.push(
      `inline constexpr std::array<mayhem::AutoNode,${r.nodes.length}> nodes = {{`,
    );
    r.nodes.forEach((n, i) => {
      const g = n.goal,
        c = resolveNodeConstraints(project, r, n);
      const markers = g?.markers?.length
        ? `markers_${i}.data(),markers_${i}.size()`
        : "nullptr,0";
      const goal = g
        ? `{{${g.x},${g.y},${g.heading}},${g.translationTolerance},${g.rotationTolerance},${g.velocityTolerance},${g.settleTime},${g.handoffRadius},mayhem::HeadingMode::${g.headingMode === "pointAt" ? "PointAt" : g.headingMode === "motion" ? "Motion" : g.headingMode === "free" ? "Free" : "Fixed"},${g.aimX ?? 0},${g.aimY ?? 0},${!!g.stop},${g.projectedHandoff ?? false},${g.profiled ?? true},${markers}}`
        : "{}";
      const next = autoNext(r, n);
      const nextIndex = next ? r.nodes.indexOf(next) : -1;
      output.push(
        `  {${quoted(n.id)},mayhem::NodeKind::${n.kind === "pose" ? "Pose" : n.kind === "finish" ? "Finish" : n.kind === "custom" ? "Custom" : "Action"},${goal},${n.timeout},${quoted(n.action ?? "")},{${c.maxVelocity},${c.maxAcceleration},${c.maxAngularVelocity},${c.maxAngularAcceleration},${c.translationKp},${c.rotationKp},${c.handoffRadius},${c.crossTrackKp},${c.minVelocity}},${n.during?.length ? `during_${i}.data(),during_${i}.size()` : "nullptr,0"},${nextIndex},${isIntermediate(r, n)}},`,
      );
    });
    output.push(
      "}};",
      `inline constexpr std::array<mayhem::AutoTransition,${r.transitions.length}> transitions = {{`,
    );
    r.transitions.forEach((t, i) =>
      output.push(
        `  {${quoted(t.id)},${quoted(t.from)},${quoted(t.to)},guard_${i}},`,
      ),
    );
    output.push(
      "}};",
      `inline constexpr mayhem::RoutineView routine{${quoted(r.id)},${quoted(r.initial)},nodes.data(),nodes.size(),transitions.data(),transitions.size()};`,
      "}",
    );
  });
  output.push("} // namespace mayhem_generated", "");
  return output.join("\n");
}
